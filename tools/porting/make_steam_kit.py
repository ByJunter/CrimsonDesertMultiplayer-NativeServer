#!/usr/bin/env python3
"""Generate kit/coop/cdmp.ini.host and cdmp.ini.guest from the profile validated with two copies.

The two-PC kit must be the live-tested profile with only the network changed, so the settings are never edited
by hand in two places. Run it after changing tools/porting/configs/cdmp.3527-2inst-*.ini.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CONFIGS = ROOT / 'tools' / 'porting' / 'configs'
KIT = ROOT / 'kit' / 'coop'

STEAM = """[steam]
; Guest: the host's SteamID64 (17 digits). Empty = the only Steam friend playing
; Crimson Desert right now. Host: empty = accepts any friend who is playing.
peer_steamid=
channel=67
recv_buffer_kb=16384
recv_buffer_messages=16384
"""


def section(text: str, name: str) -> tuple[int, int]:
    match = re.search(rf'^\[{name}\][^\n]*\n', text, re.M)
    if not match:
        raise SystemExit(f'no [{name}] section')
    following = re.search(r'^\[', text[match.end():], re.M)
    return match.start(), match.end() + following.start() if following else len(text)


def replace_section(text: str, name: str, body: str) -> str:
    start, end = section(text, name)
    return text[:start] + body.rstrip('\n') + '\n\n' + text[end:]


def generate(source: str, role: str, title: str) -> str:
    text = (CONFIGS / source).read_text(encoding='utf-8').replace('\r\n', '\n')
    first = re.search(r'^\[general\]', text, re.M)
    text = f'; Crimson Desert Multiplayer - 1.0.0.3549 - {title}\n; Generated by tools/porting/make_steam_kit.py from {source}: edit only player_name and peer_steamid.\n\n' + text[first.start():]
    text = replace_section(text, 'general', '[general]\n; Your name (the other player sees it)\nplayer_name=Player\nstartup_delay_ms=0\n')
    text = replace_section(text, 'net', f'[net]\nenabled=1\n; Through Steam, no ports to open. You must be Steam friends.\ntransport=steam\nrole={role}\nsend_rate_hz=20\n\n{STEAM}')
    # The capture is for finding bugs and writes about 10 MB a minute: 1 only when testing.
    text = re.sub(r'^record=1$', '; 1 = saves a network capture for debugging (about 25 MB a minute)\nrecord=0', text, flags=re.M)
    return text.replace('\n', '\r\n')


def main() -> None:
    KIT.mkdir(parents=True, exist_ok=True)
    for source, role, title, out in (('cdmp.3527-2inst-host.ini', 'host', 'HOST', 'cdmp.ini.host'),
                                     ('cdmp.3527-2inst-guest.ini', 'guest', 'GUEST', 'cdmp.ini.guest')):
        (KIT / out).write_bytes(generate(source, role, title).encode('utf-8'))
        print('written', KIT / out)


if __name__ == '__main__':
    main()
