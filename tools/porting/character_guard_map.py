"""Verify the 3527 character guard call chain and export short hook signatures."""
import json
import struct
from signature_map import ROOT, Pe, ImageScanner

SITES = dict(layer=(0x1F63F70,0x214EC90),layers=(0x2329700,0x2519E50),
             update=(0x85FBA0,0x944E70),post=(0x860D30,0x946060),
             restore=(0x8646D0,0x949B40),pending=(0x2329D70,0x251A650))

def main():
    pe=Pe((ROOT.parent/'bin64/CrimsonDesert.exe').read_bytes())
    assert pe.timestamp==0x6AEA07A6
    scanner=ImageScanner(pe)
    def raw(rva,n):
        off=pe.rva_to_off(rva)
        return pe.data[off:off+n]
    def call(site,target):
        assert raw(site,1)==b'\xe8' and site+5+struct.unpack('<i',raw(site+1,4))[0]==target
    call(0x945032,0x949350)
    call(0x949616,0x2519E50)
    call(0x2519FF0,0x214EC90)
    call(0x99F611,0x944E70)
    call(0x99F61E,0x946060)
    assert raw(0x949BAF,8)==bytes.fromhex('49 8b 45 40 44 38 70 30')
    call(0x949F85,0x251A650)
    assert raw(0x2519EC2,7)==bytes.fromhex('4c 39 a8 18 01 00 00')
    assert raw(0x214ECFA,3)==bytes.fromhex('48 8b 01')
    assert raw(0x214ED06,4)==bytes.fromhex('48 8b 50 10')
    result=dict(timestamp=hex(pe.timestamp), layer_chart_offset='0x118', mappings=[])
    lines=['// Generated by tools/porting/character_guard_map.py.']
    for name,(old,new) in SITES.items():
        assert scanner.function(new)['begin']==new
        head=raw(new,32)
        result['mappings'].append(dict(name=name,old=hex(old),new=hex(new),head=head.hex(' ')))
        values=', '.join(f'0x{b:02X}' for b in head)
        lines.append(f'inline constexpr uint8_t k{name.title()}3527[] = {{{values}}};')
    (ROOT/'tools/porting/data/character_guards_3527.json').write_text(json.dumps(result,indent=2)+'\n')
    (ROOT/'src/mod/game/character_guard_signatures.inc').write_text('\n'.join(lines)+'\n')
    print('Verified six function entries, call relationships, playback ABI and chart offset.')

if __name__=='__main__': main()
